CREATE TABLE clientes (
    id_cliente NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre     VARCHAR2(100 BYTE) NOT NULL,
    apellido   VARCHAR2(100 BYTE) NOT NULL,
    telefono   VARCHAR2(15 BYTE)  NOT NULL,
    email      VARCHAR2(100 BYTE) NOT NULL,
    direccion  VARCHAR2(200 BYTE) DEFAULT 'SIN ESPECIFICAR' NOT NULL,

    CONSTRAINT clientes_pk PRIMARY KEY (id_cliente),
    CONSTRAINT clientes_email_uk UNIQUE (email),
    CONSTRAINT clientes_nombre_ck CHECK (TRIM(nombre) IS NOT NULL),
    CONSTRAINT clientes_apellido_ck CHECK (TRIM(apellido) IS NOT NULL),
    CONSTRAINT clientes_telefono_ck CHECK
        (REGEXP_LIKE(telefono, '^[0-9+() -]{7,15}$')),
    CONSTRAINT clientes_email_ck CHECK
        (REGEXP_LIKE(email, '^[[:alnum:]._%+-]+@[[:alnum:].-]+\.[[:alpha:]]{2,}$')),
    CONSTRAINT clientes_direccion_ck CHECK (TRIM(direccion) IS NOT NULL)
);

CREATE TABLE vehiculos (
    id_vehiculo NUMBER GENERATED BY DEFAULT AS IDENTITY,
    marca       VARCHAR2(100 BYTE) NOT NULL,
    modelo      VARCHAR2(100 BYTE) NOT NULL,
    capacidad   NUMBER DEFAULT 1 NOT NULL,
    precio_dia  NUMBER(10,2) DEFAULT 0 NOT NULL,
    placa       VARCHAR2(20 BYTE) NOT NULL,

    CONSTRAINT vehiculos_pk PRIMARY KEY (id_vehiculo),
    CONSTRAINT vehiculos_placa_uk UNIQUE (placa),
    CONSTRAINT vehiculos_marca_ck CHECK (TRIM(marca) IS NOT NULL),
    CONSTRAINT vehiculos_modelo_ck CHECK (TRIM(modelo) IS NOT NULL),
    CONSTRAINT vehiculos_capacidad_ck CHECK (capacidad > 0),
    CONSTRAINT vehiculos_precio_ck CHECK (precio_dia >= 0),
    CONSTRAINT vehiculos_placa_ck CHECK (TRIM(placa) IS NOT NULL)
);

CREATE TABLE reservas (
    id_reserva          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_cliente          NUMBER NOT NULL,
    id_vehiculo         NUMBER NOT NULL,
    nombre_reserva      VARCHAR2(100 BYTE) NOT NULL,
    fecha_reserva       DATE DEFAULT SYSDATE NOT NULL,
    cantidad_pasajeros  NUMBER DEFAULT 1 NOT NULL,
    cantidad_dias       NUMBER DEFAULT 1 NOT NULL,
    estado              VARCHAR2(20 BYTE) DEFAULT 'CONFIRMADA' NOT NULL,
    total_pago          NUMBER(8,2) DEFAULT 0 NOT NULL,

    CONSTRAINT reservas_pk PRIMARY KEY (id_reserva),
    CONSTRAINT reservas_cliente_nombre_fecha_uk
        UNIQUE (id_cliente, nombre_reserva, fecha_reserva),
    CONSTRAINT reservas_nombre_ck CHECK (TRIM(nombre_reserva) IS NOT NULL),
    CONSTRAINT reservas_pasajeros_ck CHECK (cantidad_pasajeros > 0),
    CONSTRAINT reservas_dias_ck CHECK (cantidad_dias > 0),
    CONSTRAINT reservas_estado_ck
        CHECK (estado IN ('PENDIENTE', 'CONFIRMADA', 'CANCELADA', 'FINALIZADA')),
    CONSTRAINT reservas_pago_ck CHECK (total_pago >= 0),
    CONSTRAINT fk_reservas_clientes FOREIGN KEY (id_cliente)
        REFERENCES clientes (id_cliente),
    CONSTRAINT fk_reservas_vehiculos FOREIGN KEY (id_vehiculo)
        REFERENCES vehiculos (id_vehiculo)
);

CREATE INDEX reservas_cliente_ix ON reservas (id_cliente);
CREATE INDEX reservas_vehiculo_ix ON reservas (id_vehiculo);
